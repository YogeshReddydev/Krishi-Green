export function getCropLocalizedData(crop: SeasonalCropAdviceItem, lang: SupportedLanguage): LocalizedCropData {
  if (lang === 'te') {
    return {
      name: crop.nameTe || crop.name,
      category: crop.categoryTe || crop.category,
      sowingWindow: crop.sowingWindowTe || crop.sowingWindow,
      durationDays: crop.durationDaysTe || crop.durationDays,
      whyPlantNow: crop.whyPlantNowTe || crop.whyPlantNow,
      organicRegimen: crop.organicRegimenTe || crop.organicRegimen,
      chemicalReduction: crop.chemicalReduction,
      expectedYield: crop.expectedYieldTe || crop.expectedYield,
      estRevenue: crop.estRevenueTe || crop.estRevenue,
      riskAlert: crop.riskAlertTe || crop.riskAlert,
    };
  }

  if (lang === 'hi') {
    const hiData = HINDI_CROPS[crop.id];
    if (hiData) {
      return {
        name: hiData.name || crop.name,
        category: hiData.category || getCategoryLabel(crop.category, 'hi'),
        sowingWindow: hiData.sowingWindow || crop.sowingWindow,
        durationDays: hiData.durationDays || crop.durationDays,
        whyPlantNow: hiData.whyPlantNow || crop.whyPlantNow,
        organicRegimen: hiData.organicRegimen || crop.organicRegimen,
        chemicalReduction: hiData.chemicalReduction || crop.chemicalReduction,
        expectedYield: hiData.expectedYield || crop.expectedYield,
        estRevenue: hiData.estRevenue || crop.estRevenue,
        riskAlert: hiData.riskAlert || crop.riskAlert,
      };
    }
  }

  // General fallback for all other languages with localized category
  return {
    name: crop.name,
    category: getCategoryLabel(crop.category, lang),
    sowingWindow: crop.sowingWindow,
    durationDays: crop.durationDays,
    whyPlantNow: crop.whyPlantNow,
    organicRegimen: crop.organicRegimen,
    chemicalReduction: crop.chemicalReduction,
    expectedYield: crop.expectedYield,
    estRevenue: crop.estRevenue,
    riskAlert: crop.riskAlert,
  };
}

