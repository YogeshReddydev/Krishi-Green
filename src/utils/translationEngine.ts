/**
 * Universal Translation Hook & Engine Helper
 */
export function getUITranslation(language: SupportedLanguage) {
  const shell = UI_TRANSLATIONS[language] || UI_TRANSLATIONS.en;
  const multi = getMultiTranslations(language);
  const dict = UI_DICTIONARY[language] || UI_DICTIONARY.en;
  const cropLabels = getCropCardLabels(language);

  // Dynamic key lookup
  const t = (key: string, defaultFallback: string = ''): string => {
    if (dict[key]) return dict[key];
    if ((shell as any)[key]) return (shell as any)[key];
    if ((multi as any)[key]) return (multi as any)[key];
    if ((cropLabels as any)[key]) return (cropLabels as any)[key];
    return defaultFallback || key;
  };

  return {
    lang: language,
    isEn: language === 'en',
    isHi: language === 'hi',
    isTe: language === 'te',
    shell,
    multi,
    dict,
    cropLabels,
    t,
    getMonth: (month: number) => {
      const mData = LOCALIZED_MONTHS[month] || LOCALIZED_MONTHS[10];
      if (language === 'te') return mData.te;
      if (language === 'hi') return mData.hi;
      return mData.en;
    },
    getSeason: (month: number) => {
      const mData = LOCALIZED_MONTHS[month] || LOCALIZED_MONTHS[10];
      if (language === 'te') return mData.seasonTe;
      if (language === 'hi') return mData.seasonHi;
      return mData.seasonEn;
    },
    getRegionName: (region: RegionAgroProfile) => {
      const rData = LOCALIZED_REGIONS[region.id];
      if (language === 'te') return rData?.te || region.nameTe || region.name;
      if (language === 'hi') return rData?.hi || region.name;
      return rData?.en || region.name;
    },
    getCategory: (category: string) => getCategoryLabel(category, language),
    getCrop: (crop: SeasonalCropAdviceItem) => getCropLocalizedData(crop, language),
  };
}
